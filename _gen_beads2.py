# 严格校验
errs = []
for pname, pats in PAGES:
    if len(pats) != 8:
        errs.append(f'{pname}: patterns={len(pats)} != 8')
    for pnm, grid in pats:
        if len(grid) != 10:
            errs.append(f'{pname}/{pnm}: rows={len(grid)} != 10')
        for yi, row in enumerate(grid):
            if len(row) != 10:
                errs.append(f'{pname}/{pnm} row{yi}: len={len(row)} "{row}"')
            bad = set(row) - set('.123456')
            if bad:
                errs.append(f'{pname}/{pnm} row{yi}: bad chars {bad}')
        beads = sum(1 for row in grid for ch in row if ch in '123456')
        if not (20 <= beads <= 90):
            errs.append(f'{pname}/{pnm}: beads={beads} out of 20..90')
        print(f'{pname}/{pnm}: {beads} 颗')
if errs:
    print('!! 校验失败:')
    for e in errs:
        print(' ', e)
    raise SystemExit(1)
print('全部 16 个图样校验通过')

# 生成 JS 代码块（追加在 BEAD_PAGES 数组内）
lines = []
for pname, pats in PAGES:
    lines.append(f"  {{ name: '{pname}', patterns: [")
    for pnm, grid in pats:
        lines.append(f"    {{ name: '{pnm}', grid: [")
        for i in range(0, 10, 2):
            r1 = "'" + grid[i] + "', '" + grid[i + 1] + "',"
            lines.append('      ' + r1)
        lines[-1] = lines[-1].rstrip(',')
        lines.append('    ] },')
    lines.append('  ]},')
open('_beads2_block.js', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
