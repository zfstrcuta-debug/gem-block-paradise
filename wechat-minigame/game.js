function drawGame() {
  drawHUD();
  drawBoardBase();
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
    const px = BX + x * (CELL + GAP), py = BY + y * (CELL + GAP);
    if (!inRegion(x, y, S.reg)) { drawLockedRock(px, py); continue; }
    cellSlot(px, py);
    const v = S.board[y][x];
    if (v >= 0) drawBoardCell(v, px - 1, py - 1, CELL + 2);
  }
  drawClearFx();      // 正在消失的方块（盖在棋盘上，不盖道具栏）
  drawParticles();
  for (let i = 0; i < 3; i++) itemButton(i, ITEM_X[i], ITEM_Y, ITEM_W, ITEM_H, itemTotal(i) > 0);
  for (let i = 0; i < 3; i++) traySlot(90 + i * 180);
  S.pieces.forEach((p, i) => { if (!p.used) piece(p, 90 + i * 180, TRAY, 20); });
  if (S.drag >= 0) {
    const p = S.pieces[S.drag];
    if (inBoard(S.pos)) {
      const o = snapOrigin(p, S.pos);
      drawGhost(p, o.x, o.y, canPlace(p.cells, o.x, o.y));
    // 拖拽中的方块与棋盘格几乎等大（原来 25px vs 43px，松手会「突然变大一下」）
    } else piece(p, S.pos.x, S.pos.y, CELL - 3);
  }
  // 提示是玩家每局都要读的：归到内容小字档，但颜色提到正文级，别淡成装饰
  textCenter(S.msg, 270, 918, TYPE.body, UI.onSurface, '600');
  if (S.result === 'win') drawWin();
  else if (S.result === 'lose') drawLose();
}
function draw() {
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.fillStyle = UI.bg;
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.setTransform(dpr * scale, 0, 0, dpr * scale, dpr * ox, dpr * oy);
  if (S.scene === 'menu') drawMenu();
  else if (S.scene === 'rank') drawRank();
  else if (S.scene === 'album') { drawAlbum(); drawAlbumZoom(); }
  else if (S.scene === 'info') drawInfo();
  else drawGame();
  drawLoseHint();   // 死局道具提示（低于广告弹窗）
  drawAdDialog();   // 广告确认弹窗
  drawDaily();      // 每日任务弹窗（只在主菜单出现）
}

// ---------- 触控 ----------
function hit(x, y, x0, y0, w, h) { return x >= x0 && x <= x0 + w && y >= y0 && y <= y0 + h; }
wx.onTouchStart(e => {
  const t = toDesign(e.touches[0].clientX, e.touches[0].clientY);
  // 动效播放中：挡掉落子，避免半途改动棋盘；若 rAF 被系统挂起则强制收尾
  if (S.lock) { flushFx(); return; }
  // 每日任务弹窗
  if (S.dailyModal) {
    if (!S.daily.claimed && dailyCanClaim() && hit(t.x, t.y, 110, 564, 320, 54)) {
      if (claimDaily()) S.msg = '领取成功！三种道具各 +1（今日有效）';
      draw(); return;   // 保留弹窗，让玩家看到「已领取」
    }
    S.dailyModal = false; draw(); return;
  }
  // 广告弹窗优先
  if (S.pendingAd) {
    if (hit(t.x, t.y, 76, 492, 388, 58)) {
      if (S.pendingAd.type === 'menuReward') {
        // 主画面广告福利：进当日池（dayItems，零点清零），不消耗局内广告额度。
        // 盲盒规则：点「观看广告」才掷随机——弹窗与卡片全程不透露结果
        menuAdReset();
        const it = Math.floor(Math.random() * 3);
        S.dayItems[it] += 1;
        S.menuAd.count += 1;
        S.menuAdPulse = Date.now();
        S.menuReveal = { item: it, t0: Date.now() };   // 揭晓卡：看完广告才知道拿到什么
        saveItems(); saveMenuAd();
        vibrateFor(1);
        sfx('w4');
        pulseMenuCard();
        menuRevealLoop();
      } else {
        S.adUsed += 1; // 看完一次广告计数（模拟模式）
        if (S.pendingAd.type === 'item') {
          S.adItems[S.pendingAd.item] += 1;   // 广告道具：仅本局有效
          S.msg = '获得 ' + ITEM_NAMES[S.pendingAd.item] + ' ×1（本局有效）！';
          // 领取后保留死局提示，让玩家接着用刚领的道具
        } else if (S.pendingAd.type === 'revive') {
          if (S.mode === 'level') reviveByHammer(); else reviveHalf();
        }
      }
    }
    S.pendingAd = null;
    draw(); return;
  }
  // 死局道具提示弹窗
  if (S.loseHint) {
    const L = loseHintLayout();
    let used = false;
    for (let i = 0; i < 3; i++) {
      const bx = L.itemX0 + i * (L.itemW + L.itemGap);
      if (hit(t.x, t.y, bx, L.itemY + 3, L.itemW, L.frame.h - 6)) { useItem(i); used = true; break; }
    }
    // 巨型按钮：看广告直接敲掉方块继续（不消耗道具）——次数用完时按钮是禁用态，不响应
    if (!used && hit(t.x, t.y, L.cta.x, L.cta.y, L.cta.w, L.cta.h)) {
      if (S.adLimit - S.adUsed > 0) requestAd({ type: 'revive' });
      else S.msg = '本局广告次数已用完，用道具或重试本关';
      draw(); return;
    }
    if (!used && hit(t.x, t.y, L.b1.x, L.b1.y, L.b1.w, L.b1.h)) {
      // 不用道具 → 关掉提示，进结算画面
      S.loseHint = null; draw(); return;
    }
    if (!used && hit(t.x, t.y, L.b2.x, L.b2.y, L.b2.w, L.b2.h)) {
      // 重试本关 / 失败重来
      if (S.mode === 'level') retryLevel(); else startEndless();
      draw(); return;
    }
    draw(); return;
  }
  // 排行榜画面
  if (S.scene === 'rank') {
    if (hit(t.x, t.y, 160, 758, 220, 48)) { S.scene = 'menu'; draw(); }
    return;
  }
  // 图鉴画面：标签跳篇 + 滑动浏览 + 卡片放大 + 返回
  if (S.scene === 'album') {
    // 放大层优先：点返回按钮或面板外遮罩关闭
    if (S.albumZoom != null) {
      const z = zoomLayout();
      const outside = t.x < z.x || t.x > z.x + z.w || t.y < z.y || t.y > z.y + z.h;
      if (hit(t.x, t.y, z.btnX, z.btnY, z.btnW, z.btnH) || outside) { S.albumZoom = null; draw(); }
      return;
    }
    for (let p = 0; p < BEAD_PAGES.length; p++) {
      const tx = ALBUM_TAB.x0 + (p % ALBUM_TAB.cols) * (ALBUM_TAB.w + ALBUM_TAB.gap);
      const ty = ALBUM_TAB.y0 + Math.floor(p / ALBUM_TAB.cols) * (ALBUM_TAB.h + ALBUM_TAB.gap);
      if (hit(t.x, t.y, tx, ty, ALBUM_TAB.w, ALBUM_TAB.h)) {
        S.albumPage = p;
        S.albumScroll = Math.min(p * ALBUM_SEC_H, albumMaxScroll());
        draw(); return;
      }
    }
    if (hit(t.x, t.y, 160, 806, 220, 46)) { S.scene = 'menu'; S.albumScroll = 0; draw(); return; }
    // 记录滑动起点；同时记下点中的卡片，抬手时未滑动才放大（避免滚动误触）
    if (t.y >= ALBUM_VIEW_TOP && t.y <= ALBUM_VIEW_BOTTOM) {
      let card = null;
      const scroll = Math.min(S.albumScroll, albumMaxScroll());
      const cardW = 232, cardH = 120, gx = 28;
      for (let p = 0; p < BEAD_PAGES.length && card == null; p++) {
        const secTop = p * ALBUM_SEC_H - scroll + ALBUM_VIEW_TOP;
        if (secTop + ALBUM_SEC_H < ALBUM_VIEW_TOP || secTop > ALBUM_VIEW_BOTTOM) continue;
        for (let s = 0; s < 8; s++) {
          const cx = gx + (s % 2) * (cardW + 16);
          const cy = secTop + 36 + Math.floor(s / 2) * (cardH + 10);
          if (hit(t.x, t.y, cx, cy, cardW, cardH)) { card = p * 8 + s; break; }
        }
      }
      S.albumTouch = { y: t.y, scroll: S.albumScroll, card, moved: false };
    }
    return;
  }
  // 信息页：标签切换 / 返回 / 滑动
  if (S.scene === 'info') {
    const tabW = 156, tabGap = 8, tabX0 = 28;
    for (let i = 0; i < INFO_TABS.length; i++) {
      if (hit(t.x, t.y, tabX0 + i * (tabW + tabGap), 100, tabW, 42)) {
        S.infoPage = INFO_TABS[i].key; S.infoScroll = 0; draw(); return;
      }
    }
    if (hit(t.x, t.y, 160, 884, 220, 46)) { S.scene = 'menu'; S.infoScroll = 0; draw(); return; }
    if (t.y >= INFO_VIEW_TOP && t.y <= INFO_VIEW_BOTTOM) S.infoTouch = { y: t.y, scroll: S.infoScroll };
    return;
  }
  // 主画面
  if (S.scene === 'menu') {
    if (S.menuReveal) { S.menuReveal = null; draw(); return; }   // 揭晓卡点任意处关闭
    if (hit(t.x, t.y, DAILY_BANNER.x, DAILY_BANNER.y, DAILY_BANNER.w, DAILY_BANNER.h)) {
      // 点「领取」直接进袋，不用先开弹窗再点第二次
      if (dailyCanClaim() &&
        hit(t.x, t.y, DAILY_CTA_X, DAILY_BANNER.y + 17, DAILY_CTA_W, 40)) claimDaily();
      S.dailyModal = true; draw(); return;
    }
    const T = MENU.tiles;
    if (hit(t.x, t.y, T[0].x, T[0].y, T[0].w, T[0].h)) startLevel(resumeLevel());
    else if (hit(t.x, t.y, T[1].x, T[1].y, T[1].w, T[1].h)) startEndless();
    else if (hit(t.x, t.y, 40, MENU.quickY, 148, MENU.quickH)) showRank();
    else if (hit(t.x, t.y, 200, MENU.quickY, 148, MENU.quickH)) { S.scene = 'album'; S.albumZoom = null; }
    else if (hit(t.x, t.y, 360, MENU.quickY, 148, MENU.quickH)) shareReward();
    else if (hit(t.x, t.y, AD_CARD.x, AD_CARD.y, AD_CARD.w, AD_CARD.h)) {
      // 主画面广告福利：盲盒规则——弹窗只画「？」，看完广告才随机揭晓道具
      requestAd({ type: 'menuReward' });   // 盲盒：不预传道具，看完广告才随机揭晓
    }
    else if (t.y >= MENU.infoY && t.y <= MENU.infoY + MENU.infoH) {
      const ibW = 152, ibGap = 10, ibX0 = 32;
      const ibKeys = ['help', 'privacy', 'about'];
      for (let i = 0; i < 3; i++) {
        if (hit(t.x, t.y, ibX0 + i * (ibW + ibGap), MENU.infoY, ibW, MENU.infoH)) {
          S.scene = 'info'; S.infoPage = ibKeys[i]; S.infoScroll = 0; draw(); return;
        }
      }
    }
    draw(); return;
  }
  // 过关画面
  if (S.result === 'win') {
    if (hit(t.x, t.y, 60, 490, 200, 54)) startLevel(S.level + 1);
    else if (hit(t.x, t.y, 280, 490, 200, 54)) toMenu();
    draw(); return;
  }
  // 死局画面
  if (S.result === 'lose') {
    const L = loseLayout();
    const [b0, b1, b2] = L.b;
    if (hit(t.x, t.y, b0.x, b0.y, b0.w, b0.h)) {
      if (S.mode === 'level') retryLevel(); else requestAd({ type: 'revive' });
    } else if (hit(t.x, t.y, b1.x, b1.y, b1.w, b1.h)) {
      if (S.mode === 'level') requestAd({ type: 'revive' }); else startEndless();
    } else if (hit(t.x, t.y, b2.x, b2.y, b2.w, b2.h)) toMenu();
    draw(); return;
  }
  // 局内导航：重试 / 回主画面
  if (hit(t.x, t.y, 442, 18, 40, 40)) {
    if (S.mode === 'level') retryLevel(); else startEndless();
    draw(); return;
  }
  if (hit(t.x, t.y, 490, 18, 40, 40)) { toMenu(); draw(); return; }
  // 道具栏
  if (t.y >= ITEM_Y && t.y <= ITEM_Y + ITEM_H) {
    for (let i = 0; i < 3; i++) {
      if (hit(t.x, t.y, ITEM_X[i], ITEM_Y, ITEM_W, ITEM_H)) { useItem(i); break; }
    }
    draw(); return;
  }
  // 方块托盘
  if (t.y >= TRAY - 35 && t.y <= 925) {
    for (let i = 0; i < S.pieces.length; i++) {
      const p = S.pieces[i];
      if (!p.used && Math.abs(t.x - (90 + i * 180)) < 85) { S.drag = i; S.pos = t; break; }
    }
  }
  draw();
});
wx.onTouchMove(e => {
  // 图鉴滑动浏览
  if (S.scene === 'album' && S.albumTouch) {
    if (S.albumZoom != null) return;  // 放大层不滚动
    const t = toDesign(e.touches[0].clientX, e.touches[0].clientY);
    if (Math.abs(S.albumTouch.y - t.y) > 10) S.albumTouch.moved = true;
    S.albumScroll = Math.max(0, Math.min(albumMaxScroll(), S.albumTouch.scroll + (S.albumTouch.y - t.y)));
    S.albumPage = Math.min(BEAD_PAGES.length - 1, Math.floor((S.albumScroll + 120) / ALBUM_SEC_H));
    draw(); return;
  }
  // 信息页滑动浏览
  if (S.scene === 'info' && S.infoTouch) {
    const t = toDesign(e.touches[0].clientX, e.touches[0].clientY);
    S.infoScroll = Math.max(0, Math.min(infoMaxScroll(S.infoPage), S.infoTouch.scroll + (S.infoTouch.y - t.y)));
    draw(); return;
  }
  if (S.drag < 0) return;
  S.pos = toDesign(e.touches[0].clientX, e.touches[0].clientY);
  draw();
});
wx.onTouchEnd(() => {
  if (S.albumTouch) {
    if (!S.albumTouch.moved && S.albumTouch.card != null) { S.albumZoom = S.albumTouch.card; draw(); }
    S.albumTouch = null; return;
  }
  if (S.infoTouch) { S.infoTouch = null; return; }
  if (S.drag < 0) return;
  const idx = S.drag, p = S.pieces[idx];
  S.drag = -1;
  if (inBoard(S.pos)) {
    const o = snapOrigin(p, S.pos);
    place(idx, o.x, o.y);
  } else S.msg = '把方块拖到棋盘上试试！';
  draw();
});

