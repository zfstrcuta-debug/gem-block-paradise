  ctx.fillStyle = g;
  roundRectPath(ctx, x, y, w, h, R); ctx.fill();
  ctx.restore();
  ctx.strokeStyle = S0.border; ctx.lineWidth = 1.1;
  roundRectPath(ctx, x + 0.55, y + 0.55, w - 1.1, h - 1.1, R); ctx.stroke();

  const ink = S0.ink, size = TYPE.label;
  ctx.font = '600 ' + size + 'px ' + FONT.family;
