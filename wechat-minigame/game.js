// 深盘上的空格：离屏缓存一格（深凹坑＋顶部内阴影），100 格只贴图不重绘
let slotSprite = null;
function slotSpriteGet() {
  if (slotSprite) return slotSprite;
  const SZ = CELL * 2, RD = 11;  // 和方块圆角同值：格与块同心同圆，才像一套东西
  const cv = wx.createCanvas(); cv.width = SZ; cv.height = SZ;
  const g = cv.getContext('2d');
  // 可放置格 = 一个「凹进去的深坑」：比盘面还暗一档，上沿压得更深、底沿微亮收边
  // 盘面提到中灰之后，凹坑不能再用重黑：改成「淡淡沉下去 + 上沿一道很轻的暗」
  g.fillStyle = 'rgba(38,34,28,0.19)';
  roundRectPath(g, 0, 0, SZ, SZ, RD); g.fill();
  const lg = g.createLinearGradient(0, 0, 0, SZ);
  lg.addColorStop(0, 'rgba(38,34,28,0.17)');
  lg.addColorStop(0.42, 'rgba(38,34,28,0)');
  lg.addColorStop(1, 'rgba(255,255,255,0.07)');
  g.fillStyle = lg;
  roundRectPath(g, 0, 0, SZ, SZ, RD); g.fill();
  // 坑口：一条极轻的暗线收边（不用 2px 的死边）
  g.strokeStyle = 'rgba(38,34,28,0.16)'; g.lineWidth = 1.4;
  roundRectPath(g, 0.7, 0.7, SZ - 1.4, SZ - 1.4, RD); g.stroke();
  slotSprite = cv;
  return cv;
}
