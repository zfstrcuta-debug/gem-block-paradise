function place(idx, x0, y0) {
  const p = S.pieces[idx];
  if (!canPlace(p.cells, x0, y0)) { S.msg = '这里放不下，再试一次！'; return; }
  saveSnap();
  for (const c of p.cells) S.board[y0 + c[1]][x0 + c[0]] = cellCI(p, c);
  S.score += p.cells.length;
  p.used = true;
  const res = clearLines();   // 分数/收集/连击在这里一次结算完
  saveBest();
  // 有消除就先播动效（期间锁输入），播完再判通关/死局；没消除直接收尾
  if (res.n) startClearFx(res, finishPlace);
  else finishPlace();
}
// 落子收尾：通关双条件 → 补方块 → 死局判定
function finishPlace() {
  if (S.mode === 'level' && S.score >= S.target && goalComplete()) { doWin(); return; }
  if (S.pieces.every(q => q.used)) spawn();
  else S.over = checkOver();
  if (S.over) doLose();
  else {
    if (S.msg.indexOf('消除') < 0) S.msg = '太棒了！继续加油！';
    saveResume();   // 每手落定即暂存：接电话/杀进程都能从这一手之后继续
  }
}
// 当前正在收集的图样索引 = 已合成数量
