function drawPuzzleArt(bp, x, y, size, lit, mode) {
  const sprite = artSprite(bp), G = 4, total = G * G;
  const gap = Math.max(0.6, size * 0.006);
  const cell = (size - gap * (G - 1)) / G;
  const show = mode === 'full' ? total : mode === 'locked' ? 0 : Math.min(total, Math.floor((lit / BEAD_NEED) * total));
  const src = ART_SZ / G;
  const bg = PUZZLE_BG[bp.page] || PUZZLE_BG[0];
  // 整幅拼图的柔和主题背景（收集时也能看到画面底色，不空）
  ctx.save();
  roundRectPath(ctx, x, y, size, size, size * 0.05);
  ctx.fillStyle = bg.base; ctx.fill();
  // 背景装饰：斜向柔光带 + 小圆点，营造水彩纸质感
  ctx.clip();
  const lg = ctx.createLinearGradient(x, y, x + size, y + size);
  lg.addColorStop(0, bg.light); lg.addColorStop(1, 'rgba(255,255,255,0)');
  ctx.fillStyle = lg; ctx.fillRect(x, y, size, size);
  ctx.fillStyle = bg.dot;
  for (let i = 0; i < 5; i++) {
    const dx = x + size * (0.12 + i * 0.19), dy = y + size * (0.18 + (i % 3) * 0.28);
    ctx.beginPath(); ctx.arc(dx, dy, size * 0.012, 0, Math.PI * 2); ctx.fill();
  }
  ctx.restore();

  // 下一片要点亮的位置：呼吸光晕（把 5/16 变成「就差这一格」）
  const breath = 0.42 + 0.26 * Math.sin(Date.now() / 380);
  for (let r = 0; r < G; r++) for (let c = 0; c < G; c++) {
    const idx = r * G + c, px = x + c * (cell + gap), py = y + r * (cell + gap);
    const sx = c * src, sy = r * src;
    if (idx < show) {
      // 已获得的碎片：拼图形状 + 投影 + 顶部高光，像真的拼上去的一片
      ctx.save();
      jigsawPath(ctx, px, py, cell, cell, r, c);
      ctx.shadowColor = 'rgba(60,52,42,0.22)'; ctx.shadowBlur = size * 0.02; ctx.shadowOffsetY = size * 0.008;
      ctx.fillStyle = bg.light;   // 凸头区域超出图片矩形，先垫主题底色
      ctx.fill();
      ctx.shadowColor = 'transparent';
      ctx.clip();
      ctx.drawImage(sprite, sx, sy, src, src, px, py, cell, cell);
      ctx.restore();
      jigsawPath(ctx, px, py, cell, cell, r, c);
      ctx.strokeStyle = 'rgba(255,255,255,0.42)'; ctx.lineWidth = Math.max(0.8, size * 0.006); ctx.stroke();
      ctx.strokeStyle = 'rgba(90,80,66,0.20)'; ctx.lineWidth = Math.max(0.6, size * 0.004); ctx.stroke();
    } else {
      // 未获得：拼图凹槽（内陷），透出主题背景
      ctx.save();
      jigsawPath(ctx, px, py, cell, cell, r, c);
      ctx.fillStyle = 'rgba(38,34,28,0.10)'; ctx.fill();
      ctx.clip();
      const ig = ctx.createLinearGradient(0, py, 0, py + cell);
      ig.addColorStop(0, mode === 'locked' ? 'rgba(38,34,28,0.05)' : 'rgba(38,34,28,0.13)');
      ig.addColorStop(0.5, 'rgba(38,34,28,0)');
      ctx.fillStyle = ig; ctx.fillRect(px - cell * 0.3, py - cell * 0.3, cell * 1.6, cell * 1.6);
      ctx.restore();
      jigsawPath(ctx, px, py, cell, cell, r, c);
      ctx.strokeStyle = 'rgba(38,34,28,0.13)'; ctx.lineWidth = Math.max(0.6, size * 0.004); ctx.stroke();
      if (mode === 'progress' && idx === show && show < total) {
        // 呼吸光：暖赭描边 + 柔光，标注「下一片落在这里」
        ctx.save();
        jigsawPath(ctx, px, py, cell, cell, r, c);
        ctx.shadowColor = 'rgba(194,132,107,0.55)';
        ctx.shadowBlur = size * (0.02 + 0.014 * breath);
        ctx.strokeStyle = 'rgba(194,132,107,' + (0.35 + 0.4 * breath).toFixed(3) + ')';
        ctx.lineWidth = Math.max(1.2, size * 0.010);
        ctx.stroke();
        ctx.restore();
      }
    }
  }
}
