// 目标信息带：暖石磨砂胶囊 —— 左端达标进度环、中段收集目标、右端分数线六边形。
// v29：收集目标的宝石从 22px 放到 36px（直径放大 1.6 倍）。原来 22px 的刻面在 46 格宝石
// 面前只够当一颗小扣子，六颗排开就是一串灰点；现在宝石本身就是这一行的主角，
// 数字退到宝石下方当注释。为此胶囊从 66 加高到 80（盘面上方还有 70px 余量）。
function drawGoalBar() {
  const x = 30, y = 98, w = 480, h = 84, r = R;
  ctx.save();
  ctx.shadowColor = 'rgba(120,110,96,0.20)'; ctx.shadowBlur = 16; ctx.shadowOffsetY = 6;
  const bg = ctx.createLinearGradient(x, y, x, y + h);
  bg.addColorStop(0, UI.glassTop); bg.addColorStop(1, UI.glassBot);
  ctx.fillStyle = bg;
  roundRectPath(ctx, x, y, w, h, r); ctx.fill();
  ctx.restore();
  // 顶部受光：浅底上靠这一层撑出「磨砂玻璃」的厚度
  ctx.save();
  roundRectPath(ctx, x, y, w, h, r); ctx.clip();
  const hl = ctx.createLinearGradient(0, y, 0, y + 36);
  hl.addColorStop(0, 'rgba(255,255,255,0.66)'); hl.addColorStop(1, 'rgba(255,255,255,0)');
  ctx.fillStyle = hl; ctx.fillRect(x, y, w, 36);
  ctx.restore();
  // 框线用色票的 #CFC9BE：浅底上不靠白边（白边在米白上等于没有），靠一条暖石细线收边
  ctx.strokeStyle = 'rgba(184,174,158,0.92)'; ctx.lineWidth = 1.6;
  roundRectPath(ctx, x + 0.8, y + 0.8, w - 1.6, h - 1.6, r); ctx.stroke();

  const cy = y + h / 2;
  // ---- 左端亮片：整体推进环 ----
  const cr = 26, cx0 = x + 15 + cr;
  const hasGoal = S.mode === 'level' && !!S.goal;
  const keys = hasGoal ? Object.keys(S.goal).map(Number).sort((a, b) => a - b) : [];
  let doneCnt = 0;
  for (const k of keys) if (S.goal[k].got >= S.goal[k].need) doneCnt++;
  const aim = S.mode === 'level' ? Math.max(1, S.target) : Math.max(1, S.bestEndless);
  const pct = S.mode === 'endless' ? Math.min(1, S.score / aim)
    : hasGoal ? (keys.length ? doneCnt / keys.length : 0) : Math.min(1, S.score / S.target);
  ctx.save();
  ctx.shadowColor = 'rgba(120,110,96,0.16)'; ctx.shadowBlur = 8; ctx.shadowOffsetY = 2;
  ctx.fillStyle = UI.chip;
  ctx.beginPath(); ctx.arc(cx0, cy, cr, 0, Math.PI * 2); ctx.fill();
  ctx.restore();
  ctx.strokeStyle = 'rgba(160,148,130,0.30)'; ctx.lineWidth = 5;
  ctx.beginPath(); ctx.arc(cx0, cy, cr + 6, 0, Math.PI * 2); ctx.stroke();
  if (pct > 0) {
    ctx.strokeStyle = UI.reward; ctx.lineWidth = 5; ctx.lineCap = 'round';
    ctx.beginPath();
    ctx.arc(cx0, cy, cr + 6, -Math.PI / 2, -Math.PI / 2 + Math.PI * 2 * Math.min(1, pct));
    ctx.stroke();
    ctx.lineCap = 'butt';
  }
  if (S.mode === 'endless') {
    textCenter('×' + Math.max(0, S.adLimit - S.adUsed), cx0, cy + 5.5, 16, UI.primaryDeep, '600', 0, true);
  } else if (hasGoal) {
    textCenter(doneCnt + '/' + keys.length, cx0, cy + 6, 15, UI.primaryDeep, '600', 0, true);
  } else {
    textCenter(Math.min(100, Math.round(S.score / Math.max(1, S.target) * 100)) + '%',
      cx0, cy + 5.5, 14, UI.primaryDeep, '600', 0, true);
  }

  // ---- 右端分数框：全域圆角矩形（原六边形已移除，统一只用圆/圆角矩形） ----
  const bw = 84, bh = 56, bx0 = x + w - 15 - bw, bcx = bx0 + bw / 2;
  ctx.save();
  softShadow(ctx, 8, 3, 0.12);
  ctx.fillStyle = UI.chip;
  roundRectPath(ctx, bx0, cy - bh / 2, bw, bh, R); ctx.fill();
  ctx.restore();
  ctx.strokeStyle = 'rgba(196,166,144,0.50)'; ctx.lineWidth = 1.1;
  roundRectPath(ctx, bx0 + 0.55, cy - bh / 2 + 0.55, bw - 1.1, bh - 1.1, R); ctx.stroke();
  const badge = S.mode === 'level' ? S.target : Math.max(S.bestEndless, S.score);
  textCenter('' + badge, bcx, cy + 7.5, 21, UI.onSurface, '600', 0, true);

  // ---- 中段 ----
  const x0 = cx0 + cr + 18, x1 = bcx - bw / 2 - 14;
  if (hasGoal) {
    // 目标成组居中（不用均分）：均分会让 2~3 个目标散到整条胶囊两头，
    // 固定间距聚成一排才读得出「这是一份收集清单」。
    // 每格 = 深色小托 + 宝石 + 下方数量：深托是必须的，宝石直接贴在浅米胶囊上
    // 会读成一颗糖片，嵌进暖墨托盘才有「珠宝盒」的体积。
    const cellW = 56, gap = 10, n = keys.length;
    const totalW = n * cellW + (n - 1) * gap;
    const firstCx = (x0 + x1) / 2 - totalW / 2 + cellW / 2;
    const trayY = cy - 11, trayR = 24;
    keys.forEach((k, i) => {
      const xi = firstCx + i * (cellW + gap), g = S.goal[k], done = g.got >= g.need;
      ctx.save();
      const tg = ctx.createLinearGradient(0, trayY - trayR, 0, trayY + trayR);
      // 中调暖灰托（不是近黑）：既衬得出刻面，又不至于在浅条上凿出三个黑洞
      if (done) { tg.addColorStop(0, '#CB9576'); tg.addColorStop(1, '#AE7057'); }
      else { tg.addColorStop(0, '#7A736A'); tg.addColorStop(1, '#5B554D'); }
      ctx.fillStyle = tg;
      ctx.beginPath(); ctx.arc(xi, trayY, trayR, 0, Math.PI * 2); ctx.fill();
      // 内亮边：上沿受光、下沿回光，托盘才「凹」下去
      ctx.strokeStyle = 'rgba(255,253,246,0.26)'; ctx.lineWidth = 1.4;
      ctx.beginPath(); ctx.arc(xi, trayY, trayR - 1.4, 0, Math.PI * 2); ctx.stroke();
      if (!done) {
        // 外扩柔光：让宝石在深托里「透」出来，而不是贴在上面
        const gl = ctx.createRadialGradient(xi, trayY, 15, xi, trayY, trayR);
        gl.addColorStop(0, 'rgba(255,255,255,0.10)'); gl.addColorStop(1, 'rgba(255,255,255,0)');
        ctx.fillStyle = gl;
        ctx.beginPath(); ctx.arc(xi, trayY, trayR, 0, Math.PI * 2); ctx.fill();
      }
      ctx.restore();
      gemIcon(k, xi - 22, trayY - 22, 44);
      if (done) textCenter('✓', xi, cy + 30, 15, BTN.primary.ink, '600', 0, true);
      else textCenter(g.got + '/' + g.need, xi, cy + 30, 14.5, UI.onSurface, '600', 0, true);
    });
  } else {
    // 没有收集目标的关卡（1–4 关）与无尽模式：显示通往分数线/最高分的进度
    const bx = x0, bwid = x1 - x0, by = cy + 2, bh2 = 12;
    ctx.fillStyle = 'rgba(160,148,130,0.26)';
    roundRectPath(ctx, bx, by, bwid, bh2, 6); ctx.fill();
    const pw = Math.max(6, bwid * Math.min(1, pct));
    const pg = ctx.createLinearGradient(bx, 0, bx + pw, 0);
    pg.addColorStop(0, '#D3A184'); pg.addColorStop(1, UI.reward);
    ctx.fillStyle = pg;
    roundRectPath(ctx, bx, by, pw, bh2, 6); ctx.fill();
    const label = S.mode === 'endless'
      ? (S.score >= S.bestEndless ? '已刷新最高分' : '距最高分还差 ' + (S.bestEndless - S.score) + ' 分')
      : (S.score >= S.target ? '已达分数线' : '距分数线还差 ' + (S.target - S.score) + ' 分');
    textCenter(label, (bx + x1) / 2, cy - 9, 12.5, UI.glassSub, '', 0, S.mode !== 'endless');
  }
}
