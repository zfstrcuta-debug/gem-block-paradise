  ctx.fillStyle = bgd;
  ctx.beginPath(); ctx.arc(cx, bcy, br, 0, Math.PI * 2); ctx.fill();
  ctx.restore();
  ctx.save();
  ctx.beginPath(); ctx.arc(cx, bcy, br, 0, Math.PI * 2); ctx.clip();
  const bhl = ctx.createLinearGradient(0, bcy - br, 0, bcy + 4);
