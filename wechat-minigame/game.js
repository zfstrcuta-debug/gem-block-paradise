// 无尽模式看广告复活：清掉一半已占格，分数不清，继续本局
function reviveHalf() {
  const cells = [];
  for (let y = S.reg.s; y < S.reg.e; y++) for (let x = S.reg.s; x < S.reg.e; x++) {
    if (S.board[y][x] !== EMPTY) cells.push([x, y]);
  }
  cells.sort((a, b) => {
    const open = (p) => {
      let n = 0;
      if (p[1] > S.reg.s && S.board[p[1] - 1][p[0]] === EMPTY) n++;
      if (p[1] < S.reg.e - 1 && S.board[p[1] + 1][p[0]] === EMPTY) n++;
      if (p[0] > S.reg.s && S.board[p[1]][p[0] - 1] === EMPTY) n++;
      if (p[0] < S.reg.e - 1 && S.board[p[1]][p[0] + 1] === EMPTY) n++;
      return n;
    };
    return open(b) - open(a);
  });
  const half = Math.ceil(cells.length / 2);
  for (let i = 0; i < half; i++) S.board[cells[i][1]][cells[i][0]] = EMPTY;
  S.over = checkOver();
  if (S.over) spawn();
  clearLose('复活成功！清掉半盘，继续努力～');
}
// 敲开一块「已填格最密集」的 (2R+1)² 区域：给出真正能落子的空间。
// 死局态用道具、看广告复活都走这里，保证「腾开的位置一定放得下东西」。
function rescueOpen(R) {
  const r = R == null ? 1 : R;
  let best = null, bestCnt = 0;
  for (let y = S.reg.s; y < S.reg.e; y++) for (let x = S.reg.s; x < S.reg.e; x++) {
    let cnt = 0;
    for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
      const yy = y + dy, xx = x + dx;
      if (yy >= S.reg.s && yy < S.reg.e && xx >= S.reg.s && xx < S.reg.e && S.board[yy][xx] !== EMPTY) cnt++;
    }
    if (cnt > bestCnt) { bestCnt = cnt; best = { x, y }; }
  }
  if (!best) return false;
  for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
    const yy = best.y + dy, xx = best.x + dx;
    if (yy >= S.reg.s && yy < S.reg.e && xx >= S.reg.s && xx < S.reg.e) S.board[yy][xx] = EMPTY;
  }
  return true;
}
// 刷子（死局态）：反复重抽，直到三块里至少有一块放得下；实在不行塞 1×1 兜底
function refreshUntilFit() {
  for (let t = 0; t < 60; t++) {
    refreshPieces();
    if (!checkOver()) return true;
  }
  S.pieces = [randPiece(), randPiece(), randPiece()];
  S.pieces[0] = { cells: [[0, 0]], used: false };   // 1×1 一定放得下
  return !checkOver();
}
// 关卡看广告复活：敲掉 2 片 3×3；进度全保留
// 返回 true=解开死局可继续，false=仍死局（由调用方弹道具/重试提示）
function reviveByHammer() {
  for (let round = 0; round < 2; round++) if (!rescueOpen(1)) break;
  S.over = checkOver();
  if (S.over) {
    S.result = 'lose'; S.loseHint = 'still';
    S.msg = '敲完了还是放不下，试试道具或重试吧！'; return false;
  }
  clearLose('复活成功！敲掉两片方块，继续努力～');
  return true;
}
// 重试本关：进度清零重开（降目标已移除，分数线恢复原值）
function retryLevel() {
  startLevel(S.level);
}
// 大槌子：敲开放区里周围空格最多的已填格，分数不变
function hammerBest() {
  let bx = -1, by = -1, bestOpen = -1;
  for (let y = S.reg.s; y < S.reg.e; y++) for (let x = S.reg.s; x < S.reg.e; x++) {
    if (S.board[y][x] === EMPTY) continue;
    let open = 0;
    if (y > S.reg.s && S.board[y - 1][x] === EMPTY) open++;
    if (y < S.reg.e - 1 && S.board[y + 1][x] === EMPTY) open++;
    if (x > S.reg.s && S.board[y][x - 1] === EMPTY) open++;
    if (x < S.reg.e - 1 && S.board[y][x + 1] === EMPTY) open++;
    if (open > bestOpen) { bestOpen = open; bx = x; by = y; }
  }
  return { x: bx, y: by };
}
function refreshPieces() {
  for (let i = 0; i < S.pieces.length; i++) if (!S.pieces[i].used) S.pieces[i] = randPiece();
}
// 道具生效。**死局态的道具语义升级为「一定解围」**：
// 棋盘挤满时单敲一格／单换一组方块都腾不出空间，所以死局态改用大范围动作，
// 并在最后加一道兜底——只要还有库存被消耗掉，就必定回到游戏，不会白亏一个道具还卡在弹窗。
function useItem(i) {
  // 正常游戏中或死局提示弹窗态才可用道具；纯结算画面（win/无提示的 lose）不可用
  const inLoseHint = !!S.loseHint;
  if (S.result === 'win' || (S.over && !inLoseHint)) return;
  if (itemTotal(i) <= 0) {
    requestAd({ type: 'item', item: i }); // 模拟广告 TODO: 有流量主后接真 SDK
    return;
  }
  let acted = false, note = '';
  if (i === I_UNDO) {
    if (!S.snap) { S.msg = '还没有可以还原的步骤'; draw(); return; }
    consumeItem(i); restoreSnap(); note = '已还原上一手'; acted = true;
  } else if (i === I_HAMMER) {
    if (inLoseHint) {
      // 死局态：一片 3×3 才有意义（单格敲了等于没敲）
      saveSnap(); consumeItem(i); rescueOpen(1); note = '大槌子敲开一片'; acted = true;
    } else {
      const t = hammerBest();
      if (t.x < 0) { S.msg = '棋盘上没有可敲的方块'; draw(); return; }
      saveSnap(); consumeItem(i); S.board[t.y][t.x] = EMPTY; note = '大槌子敲掉一格'; acted = true;
    }
  } else if (i === I_REFRESH) {
    if (S.pieces.every(p => p.used)) { S.msg = '没有可刷新的方块'; draw(); return; }
    saveSnap(); consumeItem(i);
    if (inLoseHint) refreshUntilFit(); else refreshPieces();  // 死局态刷到放得下为止
    note = '方块已刷新'; acted = true;
  }
  if (acted) {
    saveItems();
    // 兜底：还原后可能还满着、刷子也刷不出空间（棋盘全满时任何形状都放不下）
    // → 再敲一片，确保「花了道具就一定回得到游戏」
    if (checkOver() && inLoseHint && rescueOpen(1) && i !== I_HAMMER) note += '，还顺手敲开一片';
    if (!checkOver()) {
      clearLose(note + '，继续加油～');   // 回到游戏画面
    } else {
      S.result = 'lose'; S.over = true; S.loseHint = 'still';
      S.msg = note + '，可还是放不下…';
    }
  }
  draw();
}

// ---------- 绘制基础 ----------
// tracking>0 时逐字绘制并加字距（标题用），num 用数字字体（分数用）
function text(s, x, y, size, color, weight, tracking, num) {
  ctx.fillStyle = color;
  const fam = num ? FONT.num : FONT.family;
  const font = (weight ? weight + ' ' : '') + size + 'px ' + fam;
  ctx.font = font;
  if (tracking) {
    let cx = x;
    for (const ch of String(s)) { ctx.fillText(ch, cx, y); cx += ctx.measureText(ch).width + tracking; }
  } else ctx.fillText(String(s), x, y);
}
// 右对齐文字：按实测宽度把起点左移，避免数量顶出按钮右缘
function textRight(s, rightX, y, size, color, weight, num) {
  ctx.font = (weight ? weight + ' ' : '') + size + 'px ' + (num ? FONT.num : FONT.family);
  text(s, rightX - ctx.measureText(String(s)).width, y, size, color, weight, 0, num);
}
// 按钮文字自动缩放：太宽就降字号，保证不溢出按钮（下限 11px）
function fitLabel(label, size, weight, maxW) {
  let s = size;
  ctx.font = (weight ? weight + ' ' : '') + s + 'px ' + FONT.family;
  while (s > 11 && ctx.measureText(label).width > maxW) {
    s -= 1;
    ctx.font = (weight ? weight + ' ' : '') + s + 'px ' + FONT.family;
  }
  return s;
}
function roundRectPath(c, x, y, w, h, r) {
  r = Math.min(r, w / 2, h / 2);
  c.beginPath();
  c.moveTo(x + r, y);
  c.lineTo(x + w - r, y);
  c.quadraticCurveTo(x + w, y, x + w, y + r);
  c.lineTo(x + w, y + h - r);
  c.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  c.lineTo(x + r, y + h);
  c.quadraticCurveTo(x, y + h, x, y + h - r);
  c.lineTo(x, y + r);
  c.quadraticCurveTo(x, y, x + r, y);
  c.closePath();
}
// 统一卡片：白底 + 细描边 + 轻薄阴影（全站卡片共用，圆角固定 R）
function panel(x, y, w, h, fill, border) {
  ctx.save();
  softShadow(ctx, 16, 4);
  ctx.fillStyle = fill || UI.surface;
  roundRectPath(ctx, x, y, w, h, R); ctx.fill();
  ctx.restore();
  ctx.strokeStyle = border || UI.outline; ctx.lineWidth = 1.3;
  roundRectPath(ctx, x + 0.65, y + 0.65, w - 1.3, h - 1.3, R); ctx.stroke();
}
// 统一按钮：全域只有三档（primary / secondary / text），样式全部来自 BTN 表。
// 旧名 filled/tonal/outlined 保留映射只为兜底，新代码一律用三档名。
function button(x, y, w, h, variant, label, size, align) {
  const key = variant === 'filled' ? 'primary'
    : (variant === 'tonal' || variant === 'outlined') ? 'secondary' : variant;
  const S0 = BTN[key] || BTN.secondary;
  ctx.save();
  softShadow(ctx, 10, 3);
  const g = ctx.createLinearGradient(0, y, 0, y + h);
  g.addColorStop(0, S0.top); g.addColorStop(1, S0.bot);
  ctx.fillStyle = g;
  // 主按钮无边框，只靠渐层与投影；次要/辅助才有 1px 同色系细边
  roundRectPath(ctx, x, y, w, h, R); ctx.fill();
  ctx.restore();
  if (S0.border) {
    ctx.strokeStyle = S0.border; ctx.lineWidth = 1.1;
    roundRectPath(ctx, x + 0.55, y + 0.55, w - 1.1, h - 1.1, R); ctx.stroke();
  }
  ctx.save();
  const weight = size >= 22 ? '600' : '';
  const fs = fitLabel(label, size, weight, w - 24);
  ctx.textAlign = align === 'left' ? 'left' : 'center'; ctx.textBaseline = 'middle';
  ctx.font = (weight ? weight + ' ' : '') + fs + 'px ' + FONT.family;
  ctx.fillStyle = S0.ink;
  ctx.fillText(label, align === 'left' ? x + 16 : x + w / 2, y + h / 2 + 1);
  ctx.restore();
}

// ---------- 6 款宝石：按「明亮式切割」的俯视图画，靠刻面明暗而不是靠颜色 ----------
const gemCache = {};
// 颜色工具：刻面需要在 base / light / dark 之间连续插值
function hex2rgb(h) {
  const v = h.replace('#', '');
  return [parseInt(v.slice(0, 2), 16), parseInt(v.slice(2, 4), 16), parseInt(v.slice(4, 6), 16)];
}
function mixHex(a, b, t) {
  const A = hex2rgb(a), B = hex2rgb(b);
  const f = v => Math.max(0, Math.min(255, Math.round(v)));
  return 'rgb(' + f(A[0] + (B[0] - A[0]) * t) + ',' + f(A[1] + (B[1] - A[1]) * t) + ',' +
    f(A[2] + (B[2] - A[2]) * t) + ')';
}
function octPath(g, cx, cy, r) {
  g.beginPath();
  for (let i = 0; i < 8; i++) {
    const a = -Math.PI / 8 + i * Math.PI / 4;
    const px = cx + Math.cos(a) * r, py = cy + Math.sin(a) * r;
    if (i) g.lineTo(px, py); else g.moveTo(px, py);
  }
  g.closePath();
}
const GEM_LIGHT = -Math.PI * 0.75;    // 光源方位：左上
// 一颗石头上一共有三阶：亮面（往 light 提）、本色、暗面（往 dark 压）
function gemShade(ci, t) {
  const gem = GEMS[ci] || { base: COLORS[ci], light: COLORS[ci], dark: COLORS[ci] };
  if (t >= 0) return mixHex(gem.base, gem.light, Math.min(1, t * 1.15));
  return mixHex(gem.base, gem.dark, Math.min(1, -t * 1.05));
}
// 在 (cx,cy) 画一颗半径 r 的刻面宝石（明亮式切割的俯视图）。
// faces：大尺寸 8 面；22px 的小图标用 4 面，8 面缩到那么小每面不足 6px 会糊成灰团。
function drawFacetGem(g, cx, cy, r, ci, faces, bright) {
  faces = faces || 8;
  bright = bright || 0;
  // 大图标（r>16，如目标条 44px）要把台面收小、反光减弱：
  // 台面按 0.46r 走，在 r=14 时只占中心 13px 不显；落到 r=22 就变成
  // 直径 20px 的白盘，整颗读作「彩色塑料片」。刻面面积必须大于台面才像切割过的石头。
  const big = r > 16;
  const R2 = r * (big ? 0.38 : 0.46), step = Math.PI * 2 / faces;
  const gem = GEMS[ci] || { base: COLORS[ci], light: COLORS[ci], dark: COLORS[ci] };
  g.save();
  octPath(g, cx, cy, r);
  g.clip();
  // 1 冠部刻面：每面按「与光源夹角」单独取色，相邻面一亮一暗才是切割过的石头
  for (let i = 0; i < faces; i++) {
    const a0 = -Math.PI / 8 + i * step, a1 = a0 + step;
    const t = Math.cos((a0 + a1) / 2 - GEM_LIGHT) * 1.14 + bright * 0.5;
    const ox0 = cx + Math.cos(a0) * r * 1.5, oy0 = cy + Math.sin(a0) * r * 1.5;
    const ox1 = cx + Math.cos(a1) * r * 1.5, oy1 = cy + Math.sin(a1) * r * 1.5;
    const tx0 = cx + Math.cos(a0) * R2, ty0 = cy + Math.sin(a0) * R2;
    const tx1 = cx + Math.cos(a1) * R2, ty1 = cy + Math.sin(a1) * R2;
    const fg = g.createLinearGradient(ox0, oy0, tx0, ty0);
    fg.addColorStop(0, gemShade(ci, t * 0.95));
    fg.addColorStop(1, gemShade(ci, t * 0.42));
    g.beginPath();
    g.moveTo(ox0, oy0); g.lineTo(ox1, oy1); g.lineTo(tx1, ty1); g.lineTo(tx0, ty0);
    g.closePath();
    g.fillStyle = fg; g.fill();
  }
  // 2 底部反光：下缘内侧一道亮光，像光穿进去又折回来（通透感的来源）
  const bl = g.createRadialGradient(cx, cy + r * 0.58, 1, cx, cy + r * 0.58, r * 0.8);
  bl.addColorStop(0, big ? 'rgba(255,255,255,0.28)' : 'rgba(255,255,255,0.44)');
  bl.addColorStop(1, 'rgba(255,255,255,0)');
  g.fillStyle = bl;
  g.fillRect(cx - r, cy - r, r * 2, r * 2);
  // 3 台面（顶面）：最亮的一块，朝光侧更白
  const tg = g.createLinearGradient(cx - R2, cy - R2, cx + R2, cy + R2);
  tg.addColorStop(0, gemShade(ci, big ? 0.86 : 1));
  tg.addColorStop(0.62, gemShade(ci, 0.50));
  tg.addColorStop(1, gemShade(ci, 0.08));
  octPath(g, cx, cy, R2);
  g.fillStyle = tg; g.fill();
  g.strokeStyle = 'rgba(255,255,255,0.52)';
  g.lineWidth = Math.max(0.8, r * 0.045);
  octPath(g, cx, cy, R2 * 0.92); g.stroke();
  // 4 棱线：每条径向棱朝光侧提亮、背光侧压暗，刻面才「立」得起来
  for (let i = 0; i < faces; i++) {
    const a = -Math.PI / 8 + i * step;
    const t = Math.cos(a - GEM_LIGHT);
    g.beginPath();
    g.moveTo(cx + Math.cos(a) * R2, cy + Math.sin(a) * R2);
    g.lineTo(cx + Math.cos(a) * r, cy + Math.sin(a) * r);
    g.strokeStyle = t > 0
      ? 'rgba(255,255,255,' + (0.16 + t * 0.32).toFixed(2) + ')'
      : 'rgba(38,44,40,' + (0.05 + (-t) * 0.13).toFixed(2) + ')';
    g.lineWidth = Math.max(0.8, r * 0.05);
    g.stroke();
  }
  // 5 星芒 + 高光点：宝石和「彩色玻璃片」最直观的差别就是这一闪
  const sx = cx - r * 0.10, sy = cy - r * 0.12;
  const sl = r * 0.50, sw = Math.max(0.9, r * 0.072);
  g.save();
  g.globalAlpha = big ? 0.52 : 0.62;
  g.fillStyle = '#FFFFFF';
  g.beginPath();
  g.moveTo(sx, sy - sl); g.lineTo(sx + sw, sy); g.lineTo(sx, sy + sl); g.lineTo(sx - sw, sy);
  g.closePath(); g.fill();
  g.beginPath();
  g.moveTo(sx - sl * 0.72, sy); g.lineTo(sx, sy - sw); g.lineTo(sx + sl * 0.72, sy); g.lineTo(sx, sy + sw);
  g.closePath(); g.fill();
  g.restore();
  g.fillStyle = 'rgba(255,255,255,0.95)';
  g.beginPath();
  g.arc(sx, sy, Math.max(1.2, r * 0.10), 0, Math.PI * 2);
  g.fill();
  g.restore();
  // 6 轮廓 + 朝光渐隐的内侧亮线（边缘反光）
  g.strokeStyle = gem.dark;
  g.lineWidth = Math.max(1, r * 0.075);
  octPath(g, cx, cy, r); g.stroke();
  const og = g.createLinearGradient(cx - r, cy - r, cx + r, cy + r);
  og.addColorStop(0, 'rgba(255,255,255,0.80)');
  og.addColorStop(0.5, 'rgba(255,255,255,0.16)');
  og.addColorStop(1, 'rgba(255,255,255,0)');
  g.strokeStyle = og;
  g.lineWidth = Math.max(0.8, r * 0.05);
  octPath(g, cx, cy, r * 0.92); g.stroke();
}
// 棋盘上的宝石 = 「方块底 + 凸起的一颗宝石」。
// 只有宝石没有底座，读起来就是一片彩色塑料片；有了方块托着，宝石才有「嵌在里面」的分量。
function gemSprite(ci) {
  const key = 'gem' + ci;
  if (gemCache[key]) return gemCache[key];
  const SZ = 96;
  const cv = wx.createCanvas();
  cv.width = SZ; cv.height = SZ;
  const g = cv.getContext('2d');
  const gem = GEMS[ci];
  // 1 底座：直接复用糖块（同色系），保证宝石块与普通块是同一个材质家族
  g.drawImage(blockSprite(ci, true), 0, 0, SZ, SZ);
  // 2 底座做一点「窝」：中心压暗衬托宝石、四角再收一档，底座退后半步
  const cx = SZ / 2, cy = SZ / 2 - 1, r = SZ * 0.33;
  g.save();
  roundRectPath(g, 2, 2, SZ - 4, SZ - 4, 11);
  g.clip();
  const vg = g.createRadialGradient(cx, cy, r * 0.5, cx, cy, SZ * 0.78);
  vg.addColorStop(0, 'rgba(30,26,20,0.22)');
  vg.addColorStop(0.60, 'rgba(30,26,20,0.12)');
  vg.addColorStop(1, 'rgba(30,26,20,0.34)');
  g.fillStyle = vg;
  g.fillRect(0, 0, SZ, SZ);
  g.restore();
  // 3 宝石落影：影子投在方块表面上，「长出来」的体积感全靠这一下
  g.save();
  g.shadowColor = 'rgba(10,8,6,0.66)';
  g.shadowBlur = 7; g.shadowOffsetY = 3.5;
  octPath(g, cx, cy, r);
  g.fillStyle = gem.dark;
  g.fill();
  g.restore();
  // 3.5 宝石外圈柔光：让它在暗底座上「透」出来，而不是贴上去
  const gl = g.createRadialGradient(cx, cy, r * 0.86, cx, cy, r * 1.5);
  gl.addColorStop(0, 'rgba(255,255,255,0.18)');
  gl.addColorStop(1, 'rgba(255,255,255,0)');
  g.fillStyle = gl;
  g.beginPath(); g.arc(cx, cy, r * 1.5, 0, Math.PI * 2); g.fill();
  // 4 宝石本体（比底座亮一档，才「长」得出来）
  drawFacetGem(g, cx, cy, r, ci, 8, 0.26);
  gemCache[key] = cv;
  return cv;
}
function drawGem(ci, x, y, size, alpha) {
  if (alpha != null) ctx.globalAlpha = alpha;
  ctx.drawImage(gemSprite(ci), x, y, size, size);
  if (alpha != null) ctx.globalAlpha = 1;
}
// 小尺寸宝石图标（目标条 22px / 主菜单 30px）：同一种刻面语言，但只切 4 面
function gemIcon(ci, x, y, size) {
  const gem = GEMS[ci] || { base: COLORS[ci], light: COLORS[ci], dark: COLORS[ci] };
  const P = Math.max(1, size * 0.06), r = (size - P * 2) / 2;
  const cx = x + size / 2, cy = y + size / 2;
  ctx.save();
  ctx.shadowColor = 'rgba(60,70,64,0.34)';
  ctx.shadowBlur = size * 0.16; ctx.shadowOffsetY = size * 0.05;
  ctx.fillStyle = gem.dark;
  octPath(ctx, cx, cy, r);
  ctx.fill();
  ctx.restore();
  drawFacetGem(ctx, cx, cy, r, ci, size >= 34 ? 8 : 4);
}
// ---------- 方块微图纹：颜色的第二重辨识通道 ----------
// 莫兰迪的通病是色相太近，快节奏下分不清。给每色压一层极淡白色几何纹，
// 辨识走「颜色 + 纹样」双通道——远看是磨砂质感，近看是可读符号。
// 纹样铺 2×2（不是 3×3）：46px 的格子里 3×3 每格不足 4px 会糊成噪点，
// 2×2 每格约 9px，符号轮廓还认得出来，而且四角露在宝石外围，宝石块也吃得到。
const GEM_PATTERN_DRAW = [
  // 0 玫瑰石：圆点
  function (g, x, y, u) { g.beginPath(); g.arc(x, y, u * 0.62, 0, Math.PI * 2); g.fill(); },
  // 1 海蓝宝：朝上的三角
  function (g, x, y, u) {
    g.beginPath(); g.moveTo(x, y - u * 0.74); g.lineTo(x + u * 0.66, y + u * 0.52);
    g.lineTo(x - u * 0.66, y + u * 0.52); g.closePath(); g.fill();
  },
  // 2 橄榄石：叶片（上下尖、两侧鼓）
  function (g, x, y, u) {
    g.beginPath(); g.moveTo(x, y - u * 0.92);
    g.quadraticCurveTo(x + u * 0.56, y, x, y + u * 0.92);
    g.quadraticCurveTo(x - u * 0.56, y, x, y - u * 0.92); g.fill();
  },
  // 3 黄水晶：圆环
  function (g, x, y, u) { g.beginPath(); g.arc(x, y, u * 0.52, 0, Math.PI * 2); g.stroke(); },
  // 4 紫水晶：菱形
  function (g, x, y, u) {
    g.beginPath(); g.moveTo(x, y - u * 0.72); g.lineTo(x + u * 0.72, y);
    g.lineTo(x, y + u * 0.72); g.lineTo(x - u * 0.72, y); g.closePath(); g.fill();
  },
  // 5 青灰石：十字
  function (g, x, y, u) {
    const t = u * 0.26, o = u * 0.76;
    g.beginPath();
    g.moveTo(x - t, y - o); g.lineTo(x + t, y - o); g.lineTo(x + t, y - t);
    g.lineTo(x + o, y - t); g.lineTo(x + o, y + t); g.lineTo(x + t, y + t);
    g.lineTo(x + t, y + o); g.lineTo(x - t, y + o); g.lineTo(x - t, y + t);
    g.lineTo(x - o, y + t); g.lineTo(x - o, y - t); g.lineTo(x - t, y - t);
    g.closePath(); g.fill();
  }
];
function drawGemPattern(g, ci, P, W, corner) {
  const fn = GEM_PATTERN_DRAW[ci];
  if (!fn) return;
  const gem = GEMS[ci];
  g.save();
  if (corner) {
    // 宝石块：底座已被「窝」压暗，纹样用白才透得出来；
    // 位置退到四角（距中心 0.315W，落在宝石半径 0.33W 之外），否则会被宝石整个吃掉。
    g.globalAlpha = 0.30;
    g.fillStyle = '#FFFFFF';
    g.strokeStyle = '#FFFFFF';
    const u = W * 0.105, off = W * 0.315;
    g.lineWidth = Math.max(1.6, u * 0.42);
    for (const sx of [-1, 1]) {
      for (const sy of [-1, 1]) fn(g, P + W / 2 + sx * off, P + W / 2 + sy * off, u);
    }
  } else {
    // 普通块：纹样用同色系的「深阶」压印。
    // 不用白——浅色块（燕麦黄 199 / 玫瑰粉 179）上白纹对比不足，等于没画；
    // 深阶纹则永远比底色暗一档，六色一律可见，又不会跳出莫兰迪的同色系。
    g.globalAlpha = 0.42;
    g.fillStyle = gem.dark;
    g.strokeStyle = gem.dark;
    const step = W / 2, u = step * 0.26;
    g.lineWidth = Math.max(1.8, u * 0.42);
    for (let r = 0; r < 2; r++) {
      for (let c = 0; c < 2; c++) fn(g, P + step * (c + 0.5), P + step * (r + 0.5), u);
    }
  }
  g.restore();
}
// 方块：3D 糖块——上亮下沉的实心渐变 + 顶部受光斜边 + 底部暗边，块间只留细缝连成一片
const blockCache = {};
function blockSprite(ci, corner) {
  const key = 'blk' + ci + (corner ? 'c' : '');
  if (blockCache[key]) return blockCache[key];
  const SZ = 96, P = 2, R = 11, W = SZ - P * 2;   // R 11 → 显示在 46px 格上约 5.3px 圆角，贴「马卡龙」手感
  const cv = wx.createCanvas(); cv.width = SZ; cv.height = SZ;
  const g = cv.getContext('2d');
  const gem = ci === OBST_IDX ? OBST
    : (GEMS[ci] || { base: COLORS[ci], light: COLORS[ci], dark: COLORS[ci] });
  // 1 落影
  g.save();
  g.shadowColor = 'rgba(10,8,6,0.46)'; g.shadowBlur = 8; g.shadowOffsetY = 3;
  g.fillStyle = gem.dark;
  roundRectPath(g, P, P, W, W, R); g.fill();
  g.restore();
  // 2 主体：顶部提亮 → 中部本色 → 底部压暗
  const vg = g.createLinearGradient(0, P, 0, P + W);
  vg.addColorStop(0, gem.light);
  vg.addColorStop(0.30, gem.base);
  vg.addColorStop(0.78, gem.base);
  vg.addColorStop(1, gem.dark);
  g.fillStyle = vg;
  roundRectPath(g, P, P, W, W, R); g.fill();
  g.save();
  roundRectPath(g, P, P, W, W, R); g.clip();
  // 3 顶部受光斜面：一条横贯的亮带，越靠上越亮
  const hg = g.createLinearGradient(0, P, 0, P + W * 0.46);
  hg.addColorStop(0, 'rgba(255,255,255,0.46)');
  hg.addColorStop(1, 'rgba(255,255,255,0)');
  g.fillStyle = hg; g.fillRect(P, P, W, W * 0.46);
  // 4 左上斜切高光：只留一点点方向感（0.045）。
  // 原本 0.15 是为了「宝石切面」，但马卡龙积木要的是圆润——斜切带会和微图纹叠成对角亮条，
  // 浅色块（燕麦黄/玫瑰粉）上尤其像「被切了一刀」。
  g.beginPath();
  g.moveTo(P, P + W * 0.42);
  g.lineTo(P + W * 0.58, P);
  g.lineTo(P + W * 0.86, P);
  g.lineTo(P, P + W * 0.72);
  g.closePath();
  g.fillStyle = 'rgba(255,255,255,0.045)'; g.fill();
  // 5 底部回光：浅盘上不需要抗「糊进深盘」，只留一点点收边
  const bg2 = g.createLinearGradient(0, P + W * 0.74, 0, P + W);
  bg2.addColorStop(0, 'rgba(255,255,255,0)');
  bg2.addColorStop(0.86, 'rgba(255,255,255,0.12)');
  bg2.addColorStop(1, 'rgba(255,255,255,0.26)');
  g.fillStyle = bg2; g.fillRect(P, P + W * 0.74, W, W * 0.26);
  // 5.5 微图纹：压在受光层之上、边框之下，跟着块的弧度走，不会显得像贴纸
  // 障碍块不加纹样：它要「沉下去」，叠上块自身的斜切高光后会变成瓦楞板，比宝石还抢眼
  if (ci !== OBST_IDX) drawGemPattern(g, ci, P, W, corner);
  g.restore();
  // 6 顶部内亮线 + 深色外沿（浅盘上靠这圈深沿提清晰度）
  g.strokeStyle = 'rgba(255,255,255,0.52)'; g.lineWidth = 2.2;
  g.beginPath();
  g.moveTo(P + R, P + 1.4); g.lineTo(P + W - R, P + 1.4);
  g.stroke();
  g.strokeStyle = gem.dark; g.lineWidth = 2;
  roundRectPath(g, P + 1, P + 1, W - 2, W - 2, R - 1); g.stroke();
  blockCache[key] = cv;
  return cv;
}
function drawBlock(ci, x, y, size, alpha) {
  if (alpha != null) ctx.globalAlpha = alpha;
  ctx.drawImage(blockSprite(ci), x, y, size, size);
  if (alpha != null) ctx.globalAlpha = 1;
}
// 障碍岩块：直接复用糖块精灵（灰版）。形状、圆角、受光斜边都跟落下来的方块一样，
// 只是颜色抽干——玩家不会误以为它是自己拖进来的一块糖。
function drawObstacle(x, y, size, alpha) {
  if (alpha != null) ctx.globalAlpha = alpha;
  ctx.drawImage(blockSprite(OBST_IDX), x, y, size, size);
  if (alpha != null) ctx.globalAlpha = 1;
}
// 按格子编码渲染：宝石(0..5) / 混搭普通块(6..11) / 障碍砖(12+)；无尽整块普通
function drawCellOf(p, c, x, y, size, alpha) {
  const ci = cellCI(p, c);
  if (isObstacle(ci)) drawObstacle(x, y, size, alpha);
  else if (S.mode === 'level' && !isBlock(ci)) drawGem(ci, x, y, size, alpha);
  else drawBlock(isBlock(ci) ? ci - BLOCK_OFFSET : ci, x, y, size, alpha);
}
function drawBoardCell(ci, x, y, size) {
  if (isObstacle(ci)) drawObstacle(x, y, size);
  else if (S.mode === 'level' && !isBlock(ci)) drawGem(ci, x, y, size);
  else drawBlock(isBlock(ci) ? ci - BLOCK_OFFSET : ci, x, y, size);
}

