// 消除特效：柔光扩散 + 方块缩小淡出（不用刺眼白闪）
// 莫兰迪体系里「白闪」是最伤质感的一招——低饱和画面被一道强白光扫过会立刻发灰发脏。
// 改成：极淡暖白柔带（0.10，原 0.34）+ 每格向外扩的同色波纹 + 方块缓慢缩小淡出，
// 传達「化开」而不是「炸开」。
function rippleColor(v) {
  if (isObstacle(v)) return OBST.light;
  const n = COLORS.length;
  const ci = v == null ? 0 : ((v % n) + n) % n;
  return GEMS[ci] ? GEMS[ci].light : COLORS[ci];
}
function drawClearFx() {
  if (!S.fx) return;
  const p = Math.min(1, (Date.now() - S.fx.t0) / S.fx.dur);
  const a = 1 - p;
  ctx.save();
  ctx.globalAlpha = 0.10 * a * a;
  ctx.fillStyle = '#FFFDF6';
  // 柔带只覆盖可玩区，别横跨到锁区去
  const gx = BX + S.reg.s * (CELL + GAP), gw = S.reg.size * (CELL + GAP);
  const gy = BY + S.reg.s * (CELL + GAP);
  for (const y of S.fx.rows) ctx.fillRect(gx, BY + y * (CELL + GAP), gw, CELL);
  for (const x of S.fx.cols) ctx.fillRect(BX + x * (CELL + GAP), gy, CELL, gw);
  ctx.restore();
  // 同色波纹：两圈错开扩散，像水面涟漪
  ctx.save();
  for (const c of S.fx.cells) {
    const cx = BX + c.x * (CELL + GAP) + CELL / 2;
    const cy = BY + c.y * (CELL + GAP) + CELL / 2;
    ctx.strokeStyle = rippleColor(c.v);
    for (let w = 0; w < 2; w++) {
      const k = (p - w * 0.17) / (1 - w * 0.17);
      if (k <= 0) continue;
      ctx.globalAlpha = 0.40 * (1 - k) * a;
      ctx.lineWidth = Math.max(1.2, CELL * 0.13 * (1 - k));
      ctx.beginPath();
      ctx.arc(cx, cy, CELL * (0.26 + 0.92 * k), 0, Math.PI * 2);
      ctx.stroke();
    }
  }
  ctx.restore();
  const sc = 1 - 0.14 * p * p;
  ctx.save();
  ctx.globalAlpha = Math.pow(a, 0.72);
  for (const c of S.fx.cells) {
    const cx = BX + c.x * (CELL + GAP) + CELL / 2;
    const cy = BY + c.y * (CELL + GAP) + CELL / 2;
    const sz = CELL * sc;
    drawBoardCell(c.v, cx - sz / 2, cy - sz / 2, sz);
  }
  ctx.restore();
  // 连击飘字：从棋盘中央弹起、放大后淡出
  if (S.combo >= 2) {
    const k = Math.min(1, p * 1.25);
    const s2 = 0.78 + 0.5 * k;
    ctx.save();
    ctx.globalAlpha = Math.max(0, 1 - k * k);
    ctx.translate(DW / 2, BY + 232);
    ctx.scale(s2, s2);
    // 深盘上白字最抢眼：配一圈深色投影把字从棋盘里托出来
    ctx.shadowColor = 'rgba(10,8,6,0.66)'; ctx.shadowBlur = 16; ctx.shadowOffsetY = 3;
    textCenter('连击 ×' + S.combo + '！', 0, 0, 40, '#FFFFFF', '600', 2, true);
    ctx.restore();
  }
}

function drawParticles() {
  if (!S.particles.length) return;
  const now = Date.now();
  ctx.save();
  for (const p of S.particles) {
    const k = (now - p.t0) / p.life;
    if (k < 0 || k > 1) continue;
    const x = p.x + p.vx * k * 60;
    const y = p.y + p.vy * k * 60 + 90 * k * k;
    ctx.globalAlpha = 1 - k;
    ctx.fillStyle = isObstacle(p.v) ? OBST.light
      : (p.v >= 0 ? COLORS[p.v % COLORS.length] : '#FCFBF6');
    ctx.beginPath(); ctx.arc(x, y, p.r * (1 - 0.5 * k), 0, Math.PI * 2); ctx.fill();
  }
  ctx.restore();
}

// ---------- 障碍布局 ----------
// 障碍不是「撒几颗」而是「砌成一片」：每关随机挑一种布局模板。
// 模板是一组比例矩形（相对可玩区 0..1，与盘面大小无关），
// 铺出来是角墩 / 中央岛 / 双墙 / 横坝 / 斜梯 / 对角 / 品字 / 上下墩——
// 在盘面上有明确轮廓，玩家一眼看出「这一整块被占住了」，而不是东一颗西一颗。
const OB_LAYOUTS = [
  { id: 'corner4', rects: [[0, 0, .20, .30], [.80, 0, .20, .30], [0, .70, .20, .30], [.80, .70, .20, .30]] },
  { id: 'island',  rects: [[.30, .30, .40, .40]] },
  { id: 'walls',   rects: [[0, .20, .20, .60], [.80, .20, .20, .60]] },
  { id: 'bars',    rects: [[.15, 0, .70, .20], [.15, .80, .70, .20]] },
  { id: 'stair',   rects: [[0, 0, .30, .20], [.175, .20, .30, .20], [.35, .40, .30, .20], [.525, .60, .30, .20], [.70, .80, .30, .20]] },
  { id: 'diag',    rects: [[0, 0, .30, .30], [.70, .70, .30, .30]] },
  { id: 'trio',    rects: [[.10, .10, .30, .30], [.60, .10, .30, .30], [.35, .60, .30, .30]] },
  { id: 'pillar',  rects: [[.35, 0, .30, .30], [.35, .70, .30, .30]] }
];
const rectArea = b => (b.x1 - b.x0 + 1) * (b.y1 - b.y0 + 1);
// 把模板换算成具体格子。预算对齐只靠「把矩形整体放大/缩小」，
// 绝不去挖单个格子——挖洞会把一块方砖变成空框或散点，就完全不是「砌成一片」了。
function obstacleCellsFor(reg, L, want) {
  const side = reg.size;
  const boxes = [];
  for (const r of L.rects) {
    const x0 = Math.max(reg.s, reg.s + Math.round(r[0] * side));
    const y0 = Math.max(reg.s, reg.s + Math.round(r[1] * side));
    const x1 = Math.min(reg.e - 1, reg.s + Math.round((r[0] + r[2]) * side) - 1);
    const y1 = Math.min(reg.e - 1, reg.s + Math.round((r[1] + r[3]) * side) - 1);
    if (x1 >= x0 && y1 >= y0) boxes.push({ x0: x0, y0: y0, x1: x1, y1: y1 });
  }
  if (!boxes.length) return [];
  const collect = () => {
    const st = new Set();
    for (const b of boxes) {
      for (let y = b.y0; y <= b.y1; y++) for (let x = b.x0; x <= b.x1; x++) st.add(y * 100 + x);
    }
    return st;
  };
  if (want != null && want > 0) {
    const midX = reg.s + side / 2, midY = reg.s + side / 2;
    // 超出预算：削面积最大的那块一条边（朝盘心那侧削，块面才不会被推到边外）
    for (let guard = 0; guard < 300 && collect().size > want; guard++) {
      let bi = 0;
      for (let i = 1; i < boxes.length; i++) if (rectArea(boxes[i]) > rectArea(boxes[bi])) bi = i;
      const b = boxes[bi], bw = b.x1 - b.x0, bh = b.y1 - b.y0;
      if (bw >= bh && bw > 0) {
        if ((b.x0 + b.x1) / 2 < midX) b.x1--; else b.x0++;
      } else if (bh > 0) {
        if ((b.y0 + b.y1) / 2 < midY) b.y1--; else b.y0++;
      } else break;
    }
    // 不足预算：挑最小的那块朝盘心长一格（长宽取较短那侧，维持方块感）
    for (let guard = 0; guard < 300 && collect().size < want; guard++) {
      let bi = 0;
      for (let i = 1; i < boxes.length; i++) if (rectArea(boxes[i]) < rectArea(boxes[bi])) bi = i;
      let grown = false;
      const order = [bi].concat(boxes.map((_, i) => i).filter(i => i !== bi));
      for (const i of order) {
        const b = boxes[i], bw = b.x1 - b.x0, bh = b.y1 - b.y0;
        const toL = (b.x0 + b.x1) / 2 < midX, toT = (b.y0 + b.y1) / 2 < midY;
        const tries = bw <= bh ? [[toL ? -1 : 1, 0], [0, toT ? -1 : 1]] : [[0, toT ? -1 : 1], [toL ? -1 : 1, 0]];
        for (const d of tries) {
          if (d[0] < 0 && b.x0 > reg.s) { b.x0--; grown = true; break; }
          if (d[0] > 0 && b.x1 < reg.e - 1) { b.x1++; grown = true; break; }
          if (d[1] < 0 && b.y0 > reg.s) { b.y0--; grown = true; break; }
          if (d[1] > 0 && b.y1 < reg.e - 1) { b.y1++; grown = true; break; }
        }
        if (grown) break;
      }
      if (!grown) break;
    }
  }
  return [...collect()].map(k => ({ x: k % 100, y: Math.floor(k / 100) }));
}
// 开局砌障碍：按预算挑面积最接近的模板（最好的两个里随机，免得每关都一个样）
function placeObstacles(ratio) {
  if (!ratio) return;
  const reg = S.reg, want = Math.round(ratio * reg.size * reg.size);
  // 8×8 上多块模板会被缩成「好几坨小墩」，反而更散；
  // 小盘面只用 1~2 块的模板（一大片 / 两墩），成片感才立得住
  const cands = OB_LAYOUTS
    .filter(L => reg.size > 8 || L.rects.length <= 2)
    .map(L => ({ L: L, n: obstacleCellsFor(reg, L, null).length }))
    .sort((a, b) => Math.abs(a.n - want) - Math.abs(b.n - want));
  const pick = cands[Math.min(cands.length - 1, Math.floor(Math.random() * 2))];
  for (const c of obstacleCellsFor(reg, pick.L, want)) S.board[c.y][c.x] = OBSTACLE;
}
// 快照不含 items（防还原刷道具）；收集进度深拷贝（防还原丢进度）
