// 拼图形状路径：每片四边按 (r+c) 奇偶交替分配凸头/凹口，相邻两片天然互扣；
// 外圈四边（r=0 / r=3 / c=0 / c=3）为平边——成品拼图的标准外形。
// tab ≈ 边长 20%，凸头外凸 / 凹口内切都走同一函数，两片画出来严丝合缝。
function jigsawPath(g, x, y, w, h, r, c) {
  const tab = Math.min(w, h) * 0.20;
  g.beginPath(); g.moveTo(x, y);
  // 上边 →右
  if (r === 0) { g.lineTo(x + w, y); }
  else {
    const mine = ((r - 1 + c) % 2) !== 0, cx = x + w / 2;
    g.lineTo(cx - tab, y);
    if (mine) g.arc(cx, y, tab, Math.PI, Math.PI * 2, false);   // 凸头朝上（归我）
    else g.arc(cx, y, tab, Math.PI, 0, true);                   // 凹口向下（让给上片）
    g.lineTo(x + w, y);
  }
  // 右边 ↓下
  if (c === 3) { g.lineTo(x + w, y + h); }
  else {
    const mine = ((r + c) % 2) === 0, cy = y + h / 2;
    g.lineTo(x + w, cy - tab);
    if (mine) g.arc(x + w, cy, tab, -Math.PI / 2, Math.PI / 2, false);  // 凸头朝右
    else g.arc(x + w, cy, tab, Math.PI * 1.5, Math.PI * 0.5, true);     // 凹口向左
    g.lineTo(x + w, y + h);
  }
  // 下边 ←左
  if (r === 3) { g.lineTo(x, y + h); }
  else {
    const mine = ((r + c) % 2) === 0, cx = x + w / 2;
    g.lineTo(cx + tab, y + h);
    if (mine) g.arc(cx, y + h, tab, 0, Math.PI, false);         // 凸头朝下
    else g.arc(cx, y + h, tab, 0, -Math.PI, true);              // 凹口向上
    g.lineTo(x, y + h);
  }
  // 左边 ↑上
  if (c === 0) { g.lineTo(x, y); }
  else {
    const mine = ((r + c - 1) % 2) !== 0, cy = y + h / 2;
    g.lineTo(x, cy + tab);
    if (mine) g.arc(x, cy, tab, Math.PI / 2, Math.PI * 1.5, false);  // 凸头朝左
    else g.arc(x, cy, tab, Math.PI / 2, -Math.PI / 2, true);         // 凹口向右
    g.lineTo(x, y);
  }
  g.closePath();
}
