// 信息页：按中文字宽自动折行
function infoWrap(s, maxW, size) {
  ctx.font = size + 'px ' + FONT.family;
  const out = []; let line = '';
  for (const ch of String(s)) {
    if (ctx.measureText(line + ch).width > maxW && line) { out.push(line); line = ch; }
    else line += ch;
  }
  if (line) out.push(line);
  return out;
}
// 信息页排版：算出每段每行的 y 与总高度（绘制与滚动条共用）
function infoLayout(page) {
  const secs = INFO_PAGES[page] || [];
  const rows = [];
  let y = INFO_VIEW_TOP + 26;  // 留出顶距，避免第一段标题被可视区裁切
  for (const sec of secs) {
    rows.push({ type: 'h', text: sec.h, y });
    y += 34;
    for (const para of sec.lines) {
      for (const ln of infoWrap(para, 430, 15)) { rows.push({ type: 'p', text: ln, y }); y += INFO_LINE_H; }
    }
    y += INFO_SEC_GAP;
  }
  return { rows, totalH: y - INFO_VIEW_TOP };
}
