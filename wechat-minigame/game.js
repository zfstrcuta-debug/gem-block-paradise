// ---------- 存档版本与迁移 ----------
const SAVE_SCHEMA = 2;   // 每次改动存档结构 +1，旧档在 loadSave 后按版本迁移

// v1 → v2 修正两处历史问题：
//  ① 旧版碎片按关卡难度分档发（最高一次 15 片），改成固定 +1 时旧值没清，
//     造成「已通关 4 关却攒到 15 片」。改以「已通关数」为唯一真相重算：
//     每首通 1 片、每合成 1 张消耗 BEAD_NEED。已合成的图样保留，不没收。
//  ② 旧档 beadDone 可能是稀疏键（如 {0:true,2:true}），而 currentBeadIdx()
//     假设索引连续，会让同一图样被重复合成、重复领道具 —— 压成 0..k-1。
function migrateSave() {
  let v = 1;
  try { v = wx.getStorageSync('schema') || 1; } catch (e) { v = 1; }
  if (v >= SAVE_SCHEMA) return;

  const doneKeys = Object.keys(S.beadDone)
    .filter(k => S.beadDone[k])
    .map(Number)
    .filter(k => k >= 0 && k < BEAD_TOTAL)
    .sort((a, b) => a - b);
  const fixed = {};
  doneKeys.forEach((k, i) => { fixed[i] = true; });
  S.beadDone = fixed;

  const clearedN = Object.keys(S.cleared).filter(k => S.cleared[k]).length;
  S.beadGot = Math.max(0, clearedN - doneKeys.length * BEAD_NEED);

  try {
    wx.setStorageSync('beadDone', S.beadDone);
    wx.setStorageSync('beadGot', S.beadGot);
    wx.setStorageSync('schema', SAVE_SCHEMA);
  } catch (e) { /* 存储失败不影响游戏 */ }
}

// 自检：碎片总量必须对得上已通关数（16 片 = 1 张图），对不上就是存档脏了
function beadAudit() {
  const clearedN = Object.keys(S.cleared).filter(k => S.cleared[k]).length;
  const doneN = currentBeadIdx();
  const total = doneN * BEAD_NEED + S.beadGot;
  return { clearedN, doneN, beadGot: S.beadGot, total, ok: total === clearedN };
}

// ---------- 关卡收集目标 ----------
// L1-4 无收集；L5-10 抽 2-3 种每种 12 颗；L11+ 抽 3-4 种每种 18 颗
// 原参数（2-3 种×20 / 4-6 种×30）远超一局能消出的目标宝石数量，L11 之后收集条件等于锁死
function makeGoal(n) {
  const t = tierOf(n);
  if (t === 0) return null;
  const kinds = t === 1 ? 2 + Math.floor(Math.random() * 2)   // 2~3
                        : 3 + Math.floor(Math.random() * 2);  // 3~4
  // C5：L21+ 每种需求量缓升（18 → 24 封顶），难度多一个维度而不是只推分数
  const need = t === 1 ? 12 : t === 2 ? 18 : 18 + Math.min(6, n - 21);
  const pool = shuffleArr([0, 1, 2, 3, 4, 5]);
  const goal = {};
  for (let i = 0; i < kinds; i++) goal[pool[i]] = { need: need, got: 0 };
  return goal;
}
function goalComplete() {
  if (!S.goal) return true;
  for (const k in S.goal) if (S.goal[k].got < S.goal[k].need) return false;
  return true;
}
function cloneGoal(src) {
  const g = {};
  for (const k in src) g[k] = { need: src[k].need, got: src[k].got };
  return g;
}

// ---------- 玩法逻辑 ----------
function shuffleArr(a) {
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}
function shapeW(shape) { return Math.max.apply(null, shape.map(c => c[0])) + 1; }
function shapeH(shape) { return Math.max.apply(null, shape.map(c => c[1])) + 1; }
// 每格自带编码：闯关=宝石(0..5)与普通块(6..11)混搭；无尽=整块单色普通方块
// 候选池先过滤：宽高不超开放区；L1-4 练习区再限 ≤4 格（排除 1×5 / 3×3）
function eligibleShapes() {
  const maxCells = (S.mode === 'level' && tierOf(S.level) === 0) ? 4 : 99;
  return SHAPES.filter(s => shapeW(s) <= S.active && shapeH(s) <= S.active && s.length <= maxCells);
}
// 闯关方块混搭：k 格里随机 1..k 颗宝石（其余普通块），宝石取 2~3 种颜色
function mixCellCodes(k) {
  const gemCount = 1 + Math.floor(Math.random() * k);
  const kinds = Math.min(gemCount, 2 + Math.floor(Math.random() * 2));
  const gemColors = shuffleArr([0, 1, 2, 3, 4, 5]).slice(0, kinds);
  const flags = [];
  for (let i = 0; i < k; i++) flags.push(i < gemCount);
  shuffleArr(flags);
  const out = [];
  for (let i = 0; i < k; i++) {
    out.push(flags[i] ? gemColors[i % kinds] : BLOCK_OFFSET + Math.floor(Math.random() * COLORS.length));
  }
  return out;
}
function randPiece() {
  const pool = eligibleShapes();
  const shape = pool[Math.floor(Math.random() * pool.length)] || SHAPES[0];
  const k = shape.length;
  let cis;
  if (S.mode === 'level') {
    cis = mixCellCodes(k);
  } else {
    const ci = Math.floor(Math.random() * COLORS.length);
    cis = shape.map(() => ci);
  }
  return { cells: shape.map((c, i) => [c[0], c[1], cis[i]]), used: false };
}
function cellCI(p, c) {
  if (c.length >= 3 && c[2] >= 0 && c[2] < BLOCK_OFFSET + COLORS.length) return c[2];
  return Math.max(0, COLORS.indexOf(p.color)); // 兼容旧存档
}
function canPlace(cells, x0, y0) {
  for (const c of cells) {
    const x = x0 + c[0], y = y0 + c[1];
    if (!inRegion(x, y, S.reg)) return false;
    if (S.board[y][x] !== EMPTY) return false;
  }
  return true;
}
function checkOver() {
  for (const p of S.pieces) {
    if (p.used) continue;
    for (let y = S.reg.s; y < S.reg.e; y++) for (let x = S.reg.s; x < S.reg.e; x++) {
      if (canPlace(p.cells, x, y)) return false;
    }
  }
  return true;
}
function spawn() {
  S.pieces = [randPiece(), randPiece(), randPiece()];
  S.over = checkOver();
  if (S.over) S.msg = '游戏结束！';
}
// ---------- 得分与连击 ----------
// 一次落子同时消 1/2/3/4+ 条的行列阶梯倍率：多列一起消，明显比逐条消划算
const LINE_MUL = [1, 1, 2.5, 4, 6];
const COMBO_STEP = 0.2, COMBO_MAX = 3;   // 连击倍率 = 1 + 0.2×(连击数-1)，上限 3×

// 满行/满列只在开放区内判定；锁区不可消除；收集目标宝石给额外积分
// 只做计算与结算；棋盘照旧立即清空，同时返回视觉层要播动画的格子快照
function clearLines() {
  const reg = S.reg, rows = [], cols = [];
  for (let y = reg.s; y < reg.e; y++) {
    let full = true;
    for (let x = reg.s; x < reg.e; x++) if (S.board[y][x] < 0) { full = false; break; }
    if (full) rows.push(y);
  }
  for (let x = reg.s; x < reg.e; x++) {
    let full = true;
    for (let y = reg.s; y < reg.e; y++) if (S.board[y][x] < 0) { full = false; break; }
    if (full) cols.push(x);
  }

  const res = { n: rows.length + cols.length, collected: 0, rows, cols, cells: [], gain: 0, combo: 0 };
  if (!res.n) { S.combo = 0; return res; }   // 这一手没消到任何一条，连击断

  if (S.mode === 'level' && S.goal) {
    const seen = {};
    const mark = (x, y) => {
      const key = y * N + x;
      if (seen[key]) return;
      seen[key] = 1;
      const v = S.board[y][x];
      if (v >= 0 && !isBlock(v) && S.goal[v]) {
        S.goal[v].got = Math.min(S.goal[v].need, S.goal[v].got + 1);
        res.collected++;
      }
    };
    for (const y of rows) for (let x = reg.s; x < reg.e; x++) mark(x, y);
    for (const x of cols) for (let y = reg.s; y < reg.e; y++) mark(x, y);
  }

  // 先把要消的格子连同颜色抓快照（行列交叉处只取一次），再清空棋盘
  const seenCell = {};
  const grab = (x, y) => {
    const k = y * N + x;
    if (seenCell[k]) return;
    seenCell[k] = 1;
    const v = S.board[y][x];
    if (v >= 0) res.cells.push({ x, y, v });
  };
  for (const y of rows) for (let x = reg.s; x < reg.e; x++) grab(x, y);
  for (const x of cols) for (let y = reg.s; y < reg.e; y++) grab(x, y);

  for (const y of rows) for (let x = reg.s; x < reg.e; x++) S.board[y][x] = EMPTY;
  for (const x of cols) for (let y = reg.s; y < reg.e; y++) S.board[y][x] = EMPTY;

  S.combo += 1;
  const mul = Math.min(COMBO_MAX, 1 + COMBO_STEP * (S.combo - 1));
  // 区域越大，填满一行越难，单条的基础价值也越高（6×6 为 1.0，10×10 为 1.67）
  const sizeMul = reg.size / 6;
  const lineScore = Math.round(res.n * 10 * sizeMul * LINE_MUL[Math.min(res.n, 4)]);
  const gain = Math.round(lineScore * mul) + res.collected * COLLECT_BONUS;
  S.score += gain;
  res.gain = gain; res.combo = S.combo;

  let m = '消除 ' + res.n + ' 条';
  if (res.n >= 2) m += ' ×' + LINE_MUL[Math.min(res.n, 4)];
  if (S.combo >= 2) m += ' · 连击 ×' + S.combo;
  m += ' · +' + gain + ' 分';
  if (res.collected) m += ' · 收集 ' + res.collected + ' 颗';
  // 连击 ×5 里程碑：当局道具随机 +1（C3）
  // 权重按店主指定：还原最容易掉、大槌子最稀有（最好的东西不能白给）
  if (S.combo === 5) {
    const r = Math.random();
    const it = r < 0.55 ? I_UNDO : r < 0.85 ? I_REFRESH : I_HAMMER;
    S.adItems[it] += 1;
    m += ' · 连击×5！' + ITEM_NAMES[it] + ' +1';
    vibrateFor(3);
  }
  S.msg = m;
  addDaily('lines', res.n);              // 每日任务：消线条数
  addDaily('gems', res.cells.length);    // 每日任务：消除宝石数
  return res;
}
// ---------- 动效：消除动画 / 粒子 / 震动 ----------
// 棋盘逻辑上落子即清空，这一层只把「正在消失的那批方块」补画一遍，
// 因此动效不会污染判定、回溯和存档。播放期间用 S.lock 挡住落子。
const FX_CLEAR_MS = 260;
let fxRafOn = false;
const nextFrame = (cb) => (typeof requestAnimationFrame === 'function'
  ? requestAnimationFrame(cb) : setTimeout(() => cb(Date.now()), 16));

// 轻震：1 条轻、2 条中、3 条以上重
function vibrateFor(n) {
  try {
    if (typeof wx.vibrateShort !== 'function') return;
    wx.vibrateShort({ type: n >= 3 ? 'heavy' : n === 2 ? 'medium' : 'light' });
  } catch (e) { /* 部分机型或静音状态不响应，忽略 */ }
}

// ---------- 音效（C4）：木琴音，WAV 打包进包体，播放失败静默 ----------
// 音高阶梯 = 连击越高越亮；done = 合成/过关的双音。mock/降级环境 SFX 为 null。
const SFX = (() => {
  try {
    if (typeof wx === 'undefined' || !wx.createInnerAudioContext) return null;
    const mk = n => {
      const a = wx.createInnerAudioContext();
      a.src = 'audio/' + n + '.wav';
      a.volume = 0.7;
      return a;
    };
    return { w1: mk('wood1'), w2: mk('wood2'), w3: mk('wood3'), w4: mk('wood4'), w5: mk('wood5'), done: mk('done') };
  } catch (e) { return null; }
})();
function sfx(name) {
  try {
    const a = SFX && SFX[name];
    if (!a) return;
    a.stop();
    a.play();
  } catch (e) { /* 音频失败不影响游戏 */ }
}

function spawnParticles(cells) {
  const t0 = Date.now();
  for (const c of cells) {
    const px = BX + c.x * (CELL + GAP) + CELL / 2;
    const py = BY + c.y * (CELL + GAP) + CELL / 2;
    for (let i = 0; i < 4; i++) {
      S.particles.push({
        x: px, y: py, v: c.v,
        vx: (Math.random() - 0.5) * 3.6,
        vy: -Math.random() * 2.8 - 0.6,
        r: 1.8 + Math.random() * 2.4,
        t0, life: 320 + Math.random() * 220
      });
    }
  }
}

function startClearFx(res, cb) {
  S.fx = { cells: res.cells, rows: res.rows, cols: res.cols, t0: Date.now(), dur: FX_CLEAR_MS, cb };
  S.lock = true;
  spawnParticles(res.cells);
  vibrateFor(res.n);
  sfx('w' + Math.min(5, Math.max(1, S.combo)));   // 音高随连击走高（C4）
  kickFx();
}

function endFx() {
  const cb = S.fx && S.fx.cb;
  S.fx = null; S.lock = false;
  if (cb) cb();
}

function tickFx() {
  const now = Date.now();
  if (S.fx && now - S.fx.t0 >= S.fx.dur) endFx();
  if (S.particles.length) S.particles = S.particles.filter(p => now - p.t0 < p.life);
  draw();
  if (S.fx || S.particles.length) nextFrame(tickFx);
  else fxRafOn = false;
}

function kickFx() {
  if (fxRafOn) return;
  fxRafOn = true;
  nextFrame(tickFx);
}

// 保险：rAF 被系统挂起时动效可能走不完，进游戏前强制收尾，避免输入被永久锁住
